// Get random spicy quote
export function getRandomQuote(): string {
  const randomIndex = Math.floor(Math.random() * motivationalQuotes.length);
  return motivationalQuotes[randomIndex];
}

// Generate viral caption with spice
export function createViralCaption(quote: string): string {
  const cta = callToActions[Math.floor(Math.random() * callToActions.length)];
  const emoji = emojis[Math.floor(Math.random() * emojis.length)];
  
  // Select 3-5 trending hashtags
  const selectedHashtags = [...trendingHashtags]
    .sort(() => 0.5 - Math.random())
    .slice(0, Math.floor(Math.random() * 3) + 3);
  
  // Format for maximum impact
  return `${emoji} ${quote}\n\n${cta}\n\n${selectedHashtags.join(" ")}`;
}

// Get quote by category
export function getQuoteByCategory(category: string): string {
  const categories: Record<string, string[]> = {
    success: motivationalQuotes.slice(0, 15),
    hustle: motivationalQuotes.slice(15, 30),
    mindset: motivationalQuotes.slice(30, 45),
    money: motivationalQuotes.slice(45, 60),
    discipline: motivationalQuotes.slice(60, 75),
    truth: motivationalQuotes.slice(75, 90),
    morning: motivationalQuotes.slice(90, 105),
    evening: motivationalQuotes.slice(105, 120),
    finance: motivationalQuotes.slice(120, 135),
    entrepreneur: motivationalQuotes.slice(135, 150)
  };
  
  const catQuotes = categories[category.toLowerCase()] || motivationalQuotes;
  return catQuotes[Math.floor(Math.random() * catQuotes.length)];
}

// Get time-based quote
export function getTimeBasedQuote(): string {
  const hour = new Date().getHours();
  
  if (hour >= 5 && hour < 12) {
    return getQuoteByCategory("morning");
  } else if (hour >= 12 && hour < 17) {
    return getQuoteByCategory("hustle");
  } else if (hour >= 17 && hour < 22) {
    return getQuoteByCategory("evening");
  } else {
    return getQuoteByCategory("mindset");
  }
}

